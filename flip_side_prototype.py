# Small bridge that gives the page the same window.claude.use('sample') interface it has on claude.ai,
# but sends requests to this local server instead.
SHIM = r"""<script>
(() => {
  const MEDIA = ['image/png','image/jpeg','image/webp','image/gif'];
  const err = (code, msg) => Object.assign(new Error(msg || code), {code});
  const toB64 = blob => new Promise((res, rej) => { const r = new FileReader(); r.onload = () => res(String(r.result).split(',')[1]); r.onerror = () => rej(err('image_rejected')); r.readAsDataURL(blob); });
  let statusP = null;
  const status = () => statusP || (statusP = fetch('/api/status').then(r => r.json()).catch(() => ({ai:false})));
  const sample = {
    async limits(){ return {images: {mediaTypes: MEDIA, maxInputBytes: 5 * 1024 * 1024, maxCount: 4}}; },
    async json(prompt, opts = {}){
      const images = [];
      for (const b of (opts.images || [])) {
        const type = MEDIA.includes(b.type) ? b.type : 'image/png';
        if (b.size > 5 * 1024 * 1024) throw err('image_rejected', 'Image too large');
        images.push({media_type: type, data: await toB64(b)});
      }
      let r;
      try { r = await fetch('/api/sample', {method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({prompt, images, tier: opts.modelTier || 'default'}), signal: opts.signal}); }
      catch (e) { if (e.name === 'AbortError') throw err('aborted'); throw err('network'); }
      const d = await r.json().catch(() => ({}));
      if (!r.ok) throw err(d.code || 'unavailable', d.message);
      return d.result;
    }
  };
  window.claude = { async use(cap){ if (cap !== 'sample') return null; const s = await status(); return s.ai ? sample : null; } };
})();
</script>"""

def load_page():
    html = gzip.decompress(base64.b64decode("".join(PAGE_GZ_B64.split()))).decode("utf-8")
    return html.replace("<head>", "<head>\n" + SHIM, 1).encode("utf-8")

def parse_json(text):
    t = text.strip()
    t = re.sub(r"^```(?:json)?\s*|\s*```$", "", t)
    try:
        return json.loads(t)
    except json.JSONDecodeError:
        m = re.search(r"\{.*\}", t, re.S)
        if m:
            return json.loads(m.group(0))
        raise

def call_claude(prompt, images, tier):
    key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if not key:
        return 503, {"code": "unavailable", "message": "No ANTHROPIC_API_KEY set"}
    content = [{"type": "image", "source": {"type": "base64", "media_type": i["media_type"], "data": i["data"]}} for i in images[:4]]
    content.append({"type": "text", "text": prompt + "\n\nReply with the JSON only, no other text."})
    body = json.dumps({"model": MODELS.get(tier, MODELS["default"]), "max_tokens": 1500,
                       "messages": [{"role": "user", "content": content}]}).encode("utf-8")
    req = urllib.request.Request(API_URL, data=body, method="POST", headers={
        "x-api-key": key, "anthropic-version": "2023-06-01", "content-type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=90) as r:
            data = json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        detail = e.read().decode("utf-8", "replace")[:300]
        code = {401: "not_granted", 403: "not_granted", 429: "rate_limited", 413: "image_rejected"}.get(e.code, "unavailable")
        if e.code == 400 and "image" in detail.lower():
            code = "image_rejected"
        print(f"  Anthropic API error {e.code}: {detail}", file=sys.stderr)
        return 502, {"code": code, "message": f"API error {e.code}"}
    except Exception as e:
        print(f"  Could not reach the Anthropic API: {e}", file=sys.stderr)
        return 502, {"code": "network", "message": "Could not reach the API"}
    text = "".join(b.get("text", "") for b in data.get("content", []) if b.get("type") == "text")
    try:
        return 200, {"result": parse_json(text)}
    except Exception:
        return 502, {"code": "bad_response", "message": "The model didn't return valid JSON"}

class Handler(BaseHTTPRequestHandler):
    page = b""
    server_version = "FlipSide/1.0"

    def log_message(self, fmt, *args):
        if "/api/" in (args[0] if args else ""):
            sys.stderr.write("  " + (fmt % args) + "\n")

    def send(self, status, body, ctype="application/json"):
        data = body if isinstance(body, bytes) else json.dumps(body).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        path = self.path.split("?")[0]
        if path in ("/", "/index.html"):
            return self.send(200, self.page, "text/html; charset=utf-8")
        if path == "/api/status":
            return self.send(200, {"ai": bool(os.environ.get("ANTHROPIC_API_KEY", "").strip())})
        if path == "/favicon.ico":
            return self.send(204, b"", "image/x-icon")
        self.send(404, {"error": "not found"})

    def do_POST(self):
        if self.path != "/api/sample":
            return self.send(404, {"error": "not found"})
        n = int(self.headers.get("Content-Length") or 0)
        if n <= 0 or n > MAX_BODY:
            return self.send(413, {"code": "image_rejected", "message": "Request too large"})
        try:
            req = json.loads(self.rfile.read(n).decode("utf-8"))
            prompt = str(req.get("prompt", ""))[:20000]
            images = [i for i in req.get("images", []) if isinstance(i, dict) and i.get("data")]
            tier = req.get("tier", "default")
        except Exception:
            return self.send(400, {"code": "bad_request", "message": "Bad request"})
        status, body = call_claude(prompt, images, tier)
        self.send(status, body)

def lan_ip():
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM); s.connect(("8.8.8.8", 80)); ip = s.getsockname()[0]; s.close(); return ip
    except Exception:
        return None

def main():
    ap = argparse.ArgumentParser(description="Run the Flip Side phone prototype locally.")
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--lan", action="store_true", help="also allow phones on the same Wi-Fi to open it")
    ap.add_argument("--no-browser", action="store_true", help="don't open a browser automatically")
    a = ap.parse_args()
    Handler.page = load_page()
    host = "0.0.0.0" if a.lan else "127.0.0.1"
    try:
        srv = ThreadingHTTPServer((host, a.port), Handler)
    except OSError:
        sys.exit(f"Port {a.port} is busy. Try: python {os.path.basename(__file__)} --port 8001")
    url = f"http://localhost:{a.port}"
    ai = bool(os.environ.get("ANTHROPIC_API_KEY", "").strip())
    print("\n  Flip Side prototype is running")
    print(f"  Open: {url}")
    if a.lan:
        ip = lan_ip()
        if ip:
            print(f"  On your phone (same Wi-Fi): http://{ip}:{a.port}")
        print("  Note: anyone on this network can use the page, and AI requests use your API key.")
    print(f"  AI features: {'ON' if ai else 'OFF (set ANTHROPIC_API_KEY to turn them on)'}")
    print("  Press Ctrl+C to stop.\n")
    if not a.no_browser:
        threading.Timer(0.6, lambda: webbrowser.open(url)).start()
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        print("\n  Stopped.")
    finally:
        srv.server_close()

if __name__ == "__main__":
    main()
